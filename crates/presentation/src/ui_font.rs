/// Returns the 8x8 monochrome glyph rows for one overlay character.
///
/// Printable ASCII resolves to the embedded font8x8 table, the sixteen
/// pseudo-locale characters resolve to their engine-owned compositions, and
/// every other character resolves to the stable placeholder box.
#[must_use]
pub fn ui_overlay_glyph_rows(glyph: char) -> [u8; 8] {
    match glyph {
        ' '..='~' => ASCII_GLYPHS[usize::from(glyph as u8 - b' ')],
        '⟦' => GLYPH_WHITE_LEFT_BRACKET,
        '⟧' => GLYPH_WHITE_RIGHT_BRACKET,
        'Ħ' => GLYPH_H_BAR,
        'ħ' => GLYPH_H_BAR_SMALL,
        'ē' => GLYPH_E_MACRON,
        'å' => GLYPH_A_RING,
        'Å' => GLYPH_A_RING_CAPITAL,
        'ł' => GLYPH_L_STROKE,
        'ŧ' => GLYPH_T_BAR,
        'ų' => GLYPH_U_OGONEK,
        'ș' => GLYPH_S_COMMA,
        'Ș' => GLYPH_S_COMMA_CAPITAL,
        'ḑ' => GLYPH_D_CEDILLA,
        'ĝ' => GLYPH_G_CIRCUMFLEX,
        'í' => GLYPH_I_ACUTE,
        'ć' => GLYPH_C_ACUTE,
        _ => GLYPH_PLACEHOLDER,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    // Every non-ASCII character used by the reference-game pseudo-locale
    // templates (crates/reference-game/src/source.rs).
    const PSEUDO_LOCALE_GLYPHS: &[char] = &[
        '⟦', '⟧', 'Ħ', 'ħ', 'ē', 'å', 'Å', 'ł', 'ŧ', 'ų', 'ș', 'Ș', 'ḑ', 'ĝ', 'í', 'ć',
    ];

    #[test]
    fn printable_ascii_resolves_to_the_embedded_table() {
        assert_eq!(ui_overlay_glyph_rows(' '), [0_u8; 8]);
        assert_eq!(
            ui_overlay_glyph_rows('!'),
            [0x18, 0x3C, 0x3C, 0x18, 0x18, 0x00, 0x18, 0x00]
        );
        assert_eq!(
            ui_overlay_glyph_rows('~'),
            [0x6E, 0x3B, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]
        );
        for glyph in '!'..='~' {
            assert_ne!(
                ui_overlay_glyph_rows(glyph),
                GLYPH_PLACEHOLDER,
                "ASCII glyph {glyph:?} must not fall back to the placeholder"
            );
        }
    }

    #[test]
    fn pseudo_locale_glyphs_are_authored_and_distinct() {
        for glyph in PSEUDO_LOCALE_GLYPHS {
            assert_ne!(
                ui_overlay_glyph_rows(*glyph),
                GLYPH_PLACEHOLDER,
                "pseudo-locale glyph {glyph:?} must be authored"
            );
        }
        assert_eq!(ui_overlay_glyph_rows('Ħ')[3], 0x7F);
        assert_eq!(ui_overlay_glyph_rows('Å')[0], 0x18);
        assert_eq!(ui_overlay_glyph_rows('Ș')[7], 0x0C);
    }

    #[test]
    fn unknown_glyph_resolves_to_the_stable_placeholder() {
        assert_eq!(ui_overlay_glyph_rows('日'), GLYPH_PLACEHOLDER);
        assert_eq!(ui_overlay_glyph_rows('\u{7f}'), GLYPH_PLACEHOLDER);
        assert_eq!(ui_overlay_glyph_rows('\n'), GLYPH_PLACEHOLDER);
    }

    #[test]
    fn glyph_lookup_is_deterministic() {
        for glyph in PSEUDO_LOCALE_GLYPHS.iter().chain("Health 37/100".chars().collect::<Vec<_>>().iter()) {
            assert_eq!(ui_overlay_glyph_rows(*glyph), ui_overlay_glyph_rows(*glyph));
        }
    }
}
